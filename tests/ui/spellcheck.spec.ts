  await expect(page.locator('.cm-misspelled',{hasText:'Vexora'})).toBeVisible({timeout:15000})
  await page.getByRole('tab',{name:'Cards',exact:true}).click();await page.getByRole('button',{name:'+ Character',exact:true}).click()
