import { test, expect } from '@playwright/test'

test('modes preserve editor, selection and history; Write hides chrome and escapes to Normal', async ({ page }) => {
  await page.goto('/'); await page.evaluate(() => localStorage.clear()); await page.reload()
  await page.getByRole('button', { name: /New writing/ }).click()
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  await editor.fill('A misspelld word.')
  await expect(page.locator('.cm-misspelled')).toHaveCount(0)
  await editor.press('Control+End'); await editor.pressSequentially(' More')
  await page.evaluate(() => { (window as any).modeEditor = document.querySelector('.cm-content') })
  await page.keyboard.press('Control+2')
  await expect(page.locator('.app')).toHaveClass(/mode-review/)
  await expect(page.locator('.cm-misspelled', { hasText: 'misspelld' })).toBeVisible()
  await page.keyboard.press('Control+1')
  await expect(page.locator('.app')).toHaveClass(/mode-write/)
  await expect(page.getByRole('banner')).toBeHidden()
  await expect(page.locator('.metadata')).toBeHidden()
  await expect(page.locator('.cm-misspelled')).toHaveCount(0)
  await editor.pressSequentially(' text')
  await page.keyboard.press('Escape')
  await expect(page.locator('.app')).toHaveClass(/mode-normal/)
  expect(await page.evaluate(() => (window as any).modeEditor === document.querySelector('.cm-content'))).toBe(true)
  await page.keyboard.press('Control+z'); await expect(editor).not.toContainText('More text')
  await page.keyboard.press('Control+2'); await page.keyboard.press('Control+s')
  await expect(page.locator('.editor-footer [role=status]')).toHaveText('All changes saved')
  await page.reload(); await expect(page.locator('.app')).toHaveClass(/mode-review/)
})

