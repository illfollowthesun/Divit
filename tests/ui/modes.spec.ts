test('Review checks mixed language paragraphs and offscreen text locally, with exact replacement and Undo', async ({ page }) => {
  await page.goto('/'); await page.evaluate(() => localStorage.clear()); await page.reload()
  await page.getByRole('button', { name: /New writing/ }).click()
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  const text = 'The ticekts were folded.\n\nTürkçe bir cümle yazıyorr.\n\n' + 'The page is here.\n\n'.repeat(100) + 'A misspelld word.'
  await editor.fill(text)
  const external: string[] = []
  page.on('request', request => { if (!request.url().startsWith(`http://127.0.0.1:${process.env.YAZI_UI_PORT ?? 1420}`) && !request.url().startsWith('data:')) external.push(request.url()) })
  await page.keyboard.press('Control+2')
  const panel = page.getByRole('complementary', { name: 'Review issues' })
  await expect(panel.getByRole('button', { name: 'misspelld', exact: true })).toBeVisible({ timeout: 15000 })
  await expect(panel.getByRole('button', { name: 'yazıyorr', exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Türkçe', exact: true })).toHaveCount(0)
  await panel.getByRole('button', { name: 'Replace ticekts with tickets', exact: true }).click()
  await page.keyboard.press('Control+s')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('yazi-browser-preview-v1')!).projects[0].body)).toBe(text.replace('ticekts', 'tickets'))
  await editor.press('Control+z'); await page.keyboard.press('Control+s')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('yazi-browser-preview-v1')!).projects[0].body)).toBe(text)
  expect(external).toEqual([])
})

test('ignore once follows one occurrence; persistent ignores and dictionaries retain language and project scope', async ({ page }) => {
  await page.goto('/'); await page.evaluate(() => localStorage.clear()); await page.reload()
  await page.getByRole('button', { name: /New writing/ }).click()
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  await editor.fill('The Zorpex Zorpex misspelld.')
  await page.keyboard.press('Control+2')
  const panel = page.getByRole('complementary', { name: 'Review issues' })
  const zorpex = panel.locator('li').filter({ has: page.getByRole('button', { name: 'Zorpex', exact: true }) })
  await expect(zorpex).toHaveCount(2)
  await zorpex.first().getByRole('button', { name: 'Ignore once', exact: true }).click()
  await expect(zorpex).toHaveCount(1)
  await editor.press('Control+Home'); await editor.pressSequentially('A ')
  await page.keyboard.press('Control+1'); await page.keyboard.press('Escape'); await page.keyboard.press('Control+2')
  await expect(zorpex).toHaveCount(1)
  await zorpex.getByRole('button', { name: 'Ignore always', exact: true }).click()
  await expect(zorpex).toHaveCount(0)
  await panel.locator('li').filter({ has: page.getByRole('button', { name: 'misspelld', exact: true }) }).getByRole('button', { name: 'Add to dictionary', exact: true }).click()
  await expect(panel.locator('li')).toHaveCount(0)
  await page.keyboard.press('Control+s')
  await expect(page.locator('.editor-footer [role=status]')).toHaveText('All changes saved')
  await page.reload(); await expect(panel.locator('li')).toHaveCount(0)
  await page.getByRole('combobox', { name: 'LANGUAGE', exact: true }).selectOption('tr')
  await expect(zorpex).toHaveCount(2, { timeout: 15000 })
  await page.getByRole('combobox', { name: 'LANGUAGE', exact: true }).selectOption('en')
  await expect(zorpex).toHaveCount(0)
  await page.keyboard.press('Control+n'); await editor.fill('Zorpex misspelld')
  await expect(zorpex).toHaveCount(1)
  await expect(panel.getByRole('button', { name: 'misspelld', exact: true })).toHaveCount(0)
})

test('mode changes preserve a long document caret and scroll position', async ({ page }) => {
  await page.goto('/'); await page.evaluate(() => localStorage.clear()); await page.reload()
  await page.getByRole('button', { name: /New writing/ }).click()
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  await editor.fill('The page is here.\n'.repeat(200))
  await editor.press('Control+Home')
  for (let i = 0; i < 70; i++) await editor.press('ArrowDown')
  const scroll = () => page.locator('.paper').evaluate(element => element.scrollTop)
  const before = await scroll()
  expect(before).toBeGreaterThan(0)
  await page.keyboard.press('Control+2')
  await expect.poll(scroll).toBeCloseTo(before, -1)
  await page.keyboard.press('Control+1')
  await expect.poll(scroll).toBeCloseTo(before, -1)
  await page.keyboard.press('Escape')
  await expect.poll(scroll).toBeCloseTo(before, -1)
  await editor.pressSequentially('INSERTED')
  await page.keyboard.press('Control+s')
  const body = await page.evaluate(() => JSON.parse(localStorage.getItem('yazi-browser-preview-v1')!).projects[0].body)
  expect(body.split('\n').findIndex((line: string) => line.includes('INSERTED'))).toBe(70)
})

