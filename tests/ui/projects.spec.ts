test('typewriter mode centers the current line without changing the text', async ({ page }) => {
  await page.getByRole('button', { name: /New writing/ }).click()
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  const text = Array.from({ length: 35 }, (_, i) => `Paragraph ${i + 1}. A little more of the story.`).join('\n\n')
  await editor.fill(text); await editor.press('Control+End')
  await page.getByRole('button', { name: 'Typewriter', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Typewriter', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(async () => page.evaluate(() => {
    const paper = document.querySelector('.paper')!, selection = window.getSelection()
    if (!selection?.rangeCount) return Number.POSITIVE_INFINITY
    const caret = selection.getRangeAt(0).getBoundingClientRect()
    return Math.abs(caret.top - paper.getBoundingClientRect().top - paper.clientHeight * 0.45)
  })).toBeLessThan(35)
  await page.keyboard.press('Control+s')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('yazi-browser-preview-v1')!).projects[0].body)).toBe(text)
  await page.keyboard.press('Control+Alt+t')
  await expect(page.getByRole('button', { name: 'Typewriter', exact: true })).toHaveAttribute('aria-pressed', 'false')
})

test('snapshots compare side by side and restoring keeps the rewrite too', async ({ page }) => {
  await startMenu(page, 'New story or book')
  await page.getByLabel('Project title').fill('The Last Ferry')
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await page.getByRole('button', { name: '+ Scene', exact: true }).click()
  await page.getByLabel('Section title').fill('The crossing')
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  await editor.fill('The sea was quiet.'); await more(page, 'Start a rewrite')
  await expect(page.getByRole('status')).toContainText('Snapshot kept')
  await editor.fill('The sea remembered every departure.')
  await more(page, 'Snapshots')
  await expect(page.locator('.snapshot-comparison section').nth(0)).toContainText('The sea was quiet.')
  await expect(page.locator('.snapshot-comparison section').nth(1)).toContainText('The sea remembered every departure.')
  await page.getByRole('button', { name: 'Restore this version', exact: true }).click()
  await expect(editor).toContainText('The sea was quiet.')
  await more(page, 'Snapshots')
  await expect(page.getByLabel('Snapshot to compare').locator('option')).toHaveCount(2)
  await expect(page.locator('.snapshot-comparison section').nth(0)).toContainText('The sea remembered every departure.')
})

test('browser preview exports a real Markdown download with the built-in exporter', async ({ page }) => {
  await startMenu(page, 'New story or book')
  await page.getByLabel('Project title').fill('İstanbul at dawn')
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await page.getByRole('button', { name: '+ Scene', exact: true }).click()
  await page.getByLabel('Section title').fill('The crossing')
  await page.getByRole('textbox', { name: 'Markdown text' }).fill('The ferry left before the city woke.')
  await page.getByRole('button', { name: 'Export', exact: true }).click(); await page.getByLabel('Export format').selectOption('markdown')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export manuscript', exact: true }).click()
  const download = await pending, content = await readFile((await download.path())!, 'utf8')
  expect(content).toContain('İstanbul at dawn'); expect(content).toContain('# The crossing')
  expect(content).toContain('The ferry left before the city woke.')
  expect(download.suggestedFilename()).toMatch(/\.md$/)
  await expect(page.locator('.export-result')).toContainText('Copy ready')
})

