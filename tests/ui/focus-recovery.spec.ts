import { test, expect } from '@playwright/test'

test('Research drawer is modal across the 1100–1240 boundary', async ({ page }) => {
  await page.setViewportSize({ width: 1180, height: 850 })
  await page.goto('/')
  await page.getByRole('button', { name: /New writing/ }).click()
  await page.keyboard.press('Control+Alt+r')
  const panel = page.locator('#writing-companion')
  await expect(panel).toHaveClass(/right-drawer/)
  await expect(panel).toBeVisible()
  await expect(page.locator('.drawer-scrim')).toBeVisible()
  await expect(page.locator('.writing-area')).toHaveAttribute('inert', '')
  const close = page.getByRole('button', { name: 'Close side panel', exact: true })
  await expect(close).toBeVisible()
  await close.focus(); await page.keyboard.press('Shift+Tab')
  expect(await panel.evaluate(el => el.contains(document.activeElement))).toBe(true)
  await close.click()
  await expect(panel).toBeHidden()
  await expect(page.locator('.document-toolbar').getByRole('button', { name: 'Side panel', exact: true })).toBeFocused()
  await page.keyboard.press('Control+Alt+r')
  await page.setViewportSize({ width: 1240, height: 850 })
  await expect(panel).not.toHaveClass(/right-drawer/)
  await expect(page.locator('.writing-area')).not.toHaveAttribute('inert', '')
  await page.setViewportSize({ width: 1239, height: 850 })
  await page.keyboard.press('Control+Alt+r')
  await expect(page.locator('.drawer-scrim')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
})

test('Focus shortcut works in Write mode without losing the draft', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /New writing/ }).click()
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  await editor.fill('SIS-268 isolated regression text.')
  await page.keyboard.press('Control+.')
  await page.keyboard.press('Control+1')
  await expect(page.locator('.app')).toHaveClass(/mode-write/)
  await page.keyboard.press('Control+.')
  await expect(page.locator('.app')).toHaveClass(/focus-mode/)
  await page.keyboard.press('Control+.')
  await expect(page.locator('.app')).not.toHaveClass(/focus-mode/)
  await expect(page.locator('.app')).toHaveClass(/mode-write/)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+.')
  await page.mouse.move(600, 600)
  await page.locator('.focus-exit').click()
  await expect(editor).toBeFocused()
  await page.keyboard.press('Control+s')
  await expect(page.locator('.save-state')).toHaveText('Saved')
  await page.reload()
  await expect(editor).toHaveText('SIS-268 isolated regression text.')
  await page.keyboard.press('Control+3')
  await page.keyboard.press('Control+s')
  await expect(page.locator('.save-state')).toHaveText('Saved')
})

test('touch can leave Focus even in Write mode', async ({ browser }) => {
  const context = await browser.newContext({ hasTouch: true })
  const page = await context.newPage()
  await page.goto('/')
  await page.getByRole('button', { name: /New writing/ }).tap()
  await page.keyboard.press('Control+1')
  await page.keyboard.press('Control+.')
  await page.locator('.focus-exit').tap()
  await expect(page.locator('.app')).not.toHaveClass(/focus-mode/)
  await expect(page.getByRole('textbox', { name: 'Markdown text' })).toBeFocused()
  await context.close()
})

test('Focus survives modes, Typewriter, Research, resizing and theme changes', async ({ page }) => {
  test.setTimeout(60000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: /New writing/ }).click()
  const editor = page.getByRole('textbox', { name: 'Markdown text' })
  await editor.fill('Isolated text remains through view changes.')
  for (const width of [1000, 1180, 1440]) {
    await page.setViewportSize({ width, height: 850 })
    for (const mode of ['1', '2', '3']) {
      await page.keyboard.press('Control+3')
      await page.keyboard.press('Control+Alt+r')
      await page.keyboard.press('Escape')
      await page.keyboard.press('Control+Alt+t')
      await page.keyboard.press(`Control+${mode}`)
      await page.keyboard.press('Control+.')
      await expect(page.locator('.app')).toHaveClass(/focus-mode/)
      await expect(editor).toBeFocused()
      await page.keyboard.press('Control+.')
      await expect(page.locator('.app')).not.toHaveClass(/focus-mode/)
      await page.keyboard.press('Escape')
      await expect(editor).toHaveText('Isolated text remains through view changes.')
    }
  }
  await page.keyboard.press('Control+,')
  await page.getByRole('dialog').getByRole('tab', { name: 'Appearance', exact: true }).click()
  await page.locator('#settings-theme').selectOption('dark')
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  await page.keyboard.press('Control+.'); await page.keyboard.press('Escape')
  await page.keyboard.press('Control+s')
  await expect(page.locator('.save-state')).toHaveText('Saved')
  await page.reload()
  await expect(editor).toHaveText('Isolated text remains through view changes.')
  expect(errors).toEqual([])
})

test('runtime breadcrumbs survive reload and omit error text and writing', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => {
    window.dispatchEvent(new ErrorEvent('error', { error: new TypeError('PRIVATE-SENTINEL-TEXT') }))
    window.dispatchEvent(new PromiseRejectionEvent('unhandledrejection', { promise: Promise.resolve(), reason: 'PRIVATE-SENTINEL-KEY' }))
  })
  const read = () => page.evaluate(() => localStorage.getItem('divit-runtime-diagnostics-v1') ?? '')
  await expect.poll(read).toContain('script-error')
  expect(await read()).not.toContain('PRIVATE-SENTINEL')
  await page.reload()
  await expect.poll(read).toContain('rejection')
  expect(JSON.parse(await read()).length).toBeLessThanOrEqual(40)
})
